// Host reference (independent of the GPU code): plain modular arithmetic, affine points
// ============================================================================
typedef std::vector<u32> U;   // 8 LE words
static const u32 HP[8] = { 0xFFFFFC2Fu, 0xFFFFFFFEu, 0xFFFFFFFFu, 0xFFFFFFFFu, 0xFFFFFFFFu, 0xFFFFFFFFu, 0xFFFFFFFFu, 0xFFFFFFFFu };
static const u32 HN[8] = N_WORDS;
static int hcmp(const u32 *a, const u32 *b) { for (int i = 7; i >= 0; i--) if (a[i] != b[i]) return a[i] < b[i] ? -1 : 1; return 0; }
static void hsub_raw(u32 *r, const u32 *a, const u32 *b) { u64 br = 0; for (int i = 0; i < 8; i++) { u64 t = (u64)a[i] - b[i] - br; r[i] = (u32)t; br = (t >> 63) & 1; } }
static u32 hadd_raw(u32 *r, const u32 *a, const u32 *b) { u64 c = 0; for (int i = 0; i < 8; i++) { c += (u64)a[i] + b[i]; r[i] = (u32)c; c >>= 32; } return (u32)c; }
static void hmod(u32 *r, const u32 *m) { while (hcmp(r, m) >= 0) hsub_raw(r, r, m); }
static void haddm(u32 *r, const u32 *a, const u32 *b, const u32 *m) {   // a, b < m
    u32 t[8]; u32 c = hadd_raw(t, a, b);
    if (c || hcmp(t, m) >= 0) hsub_raw(t, t, m);
    memcpy(r, t, 32);
}
static void hsubm(u32 *r, const u32 *a, const u32 *b, const u32 *m) {
    u32 t[8];
    if (hcmp(a, b) >= 0) hsub_raw(t, a, b); else { hsub_raw(t, a, b); hadd_raw(t, t, m); }
    memcpy(r, t, 32);
}
static void hmulp(u32 *r, const u32 *a, const u32 *b) {   // mod p, schoolbook + repeated fold
    u64 t[17] = {0};
    for (int i = 0; i < 8; i++) { u64 c = 0; for (int j = 0; j < 8; j++) { u64 v = t[i + j] + (u64)a[i] * b[j] + c; t[i + j] = (u32)v; c = v >> 32; } t[i + 8] += c; }
    // fold t_hi * (2^32 + 977) into t_lo until the top is zero
    for (int pass = 0; pass < 4; pass++) {
        u64 hi[9]; for (int i = 0; i < 9; i++) { hi[i] = t[8 + i]; t[8 + i] = 0; }
        for (int i = 0; i < 9; i++) {
            u64 c = hi[i] * 977;
            for (int j = i; c && j < 17; j++) { u64 v = t[j] + (c & 0xffffffffu); t[j] = (u32)v; c = (c >> 32) + (v >> 32); }
            c = hi[i];
            for (int j = i + 1; c && j < 17; j++) { u64 v = t[j] + (c & 0xffffffffu); t[j] = (u32)v; c = (c >> 32) + (v >> 32); }
        }
    }
    for (int i = 0; i < 8; i++) r[i] = (u32)t[i];
    hmod(r, HP);
}
static void hpowp(u32 *r, const u32 *a, const u32 *e) {
    u32 acc[8] = {1, 0, 0, 0, 0, 0, 0, 0}, base[8];
    memcpy(base, a, 32);
    for (int i = 0; i < 256; i++) { if ((e[i >> 5] >> (i & 31)) & 1) hmulp(acc, acc, base); hmulp(base, base, base); }
    memcpy(r, acc, 32);
}
static void hinvp(u32 *r, const u32 *a) { u32 e[8]; memcpy(e, HP, 32); e[0] -= 2; hpowp(r, a, e); }
struct HPt { u32 x[8], y[8]; bool inf; };
static HPt hadd(const HPt &p, const HPt &q) {
    if (p.inf) return q;
    if (q.inf) return p;
    u32 l[8], t[8], u[8];
    if (hcmp(p.x, q.x) == 0) {
        u32 s[8]; haddm(s, p.y, q.y, HP);
        bool zero = true; for (int i = 0; i < 8; i++) zero &= s[i] == 0;
        if (zero) { HPt o; o.inf = true; return o; }
        u32 three[8] = {3, 0, 0, 0, 0, 0, 0, 0}, two[8] = {2, 0, 0, 0, 0, 0, 0, 0};
        hmulp(t, p.x, p.x); hmulp(t, t, three); hmulp(u, p.y, two); hinvp(u, u); hmulp(l, t, u);
    } else {
        hsubm(t, q.y, p.y, HP); hsubm(u, q.x, p.x, HP); hinvp(u, u); hmulp(l, t, u);
    }
    HPt o; o.inf = false;
    hmulp(t, l, l); hsubm(t, t, p.x, HP); hsubm(o.x, t, q.x, HP);
    hsubm(t, p.x, o.x, HP); hmulp(t, l, t); hsubm(o.y, t, p.y, HP);
    return o;
}
static HPt hG() {
    HPt g; g.inf = false;
    const u32 gx[8] = { 0x16F81798u, 0x59F2815Bu, 0x2DCE28D9u, 0x029BFCDBu, 0xCE870B07u, 0x55A06295u, 0xF9DCBBACu, 0x79BE667Eu };
    const u32 gy[8] = { 0xFB10D4B8u, 0x9C47D08Fu, 0xA6855419u, 0xFD17B448u, 0x0E1108A8u, 0x5DA4FBFCu, 0x26A3C465u, 0x483ADA77u };
    memcpy(g.x, gx, 32); memcpy(g.y, gy, 32);
    return g;
}
static HPt hmulG(const u32 *k) {
    HPt r; r.inf = true; HPt q = hG();
    for (int i = 0; i < 256; i++) { if ((k[i >> 5] >> (i & 31)) & 1) r = hadd(r, q); q = hadd(q, q); }
    return r;
}

static const u64 HKRC[24] = {
    0x0000000000000001ULL, 0x0000000000008082ULL, 0x800000000000808aULL, 0x8000000080008000ULL,
    0x000000000000808bULL, 0x0000000080000001ULL, 0x8000000080008081ULL, 0x8000000000008009ULL,
    0x000000000000008aULL, 0x0000000000000088ULL, 0x0000000080008009ULL, 0x000000008000000aULL,
    0x000000008000808bULL, 0x800000000000008bULL, 0x8000000000008089ULL, 0x8000000000008003ULL,
    0x8000000000008002ULL, 0x8000000000000080ULL, 0x000000000000800aULL, 0x800000008000000aULL,
    0x8000000080008081ULL, 0x8000000000008080ULL, 0x0000000080000001ULL, 0x8000000080008008ULL };
static void hkeccak256(const u8 *in, size_t len, u8 out[32]) {   // len < 136
    u64 s[25] = {0};
    u8 blk[136] = {0};
    memcpy(blk, in, len); blk[len] ^= 0x01; blk[135] ^= 0x80;
    for (int i = 0; i < 17; i++) { u64 v = 0; for (int b = 7; b >= 0; b--) v = (v << 8) | blk[8 * i + b]; s[i] ^= v; }
    static const int R[5][5] = { {0, 36, 3, 41, 18}, {1, 44, 10, 45, 2}, {62, 6, 43, 15, 61}, {28, 55, 25, 21, 56}, {27, 20, 39, 8, 14} };
    auto rl = [](u64 x, int n) { return n ? (x << n) | (x >> (64 - n)) : x; };
    for (int r = 0; r < 24; r++) {
        u64 C[5], D[5], B[25];
        for (int x = 0; x < 5; x++) C[x] = s[x] ^ s[x + 5] ^ s[x + 10] ^ s[x + 15] ^ s[x + 20];
        for (int x = 0; x < 5; x++) D[x] = C[(x + 4) % 5] ^ rl(C[(x + 1) % 5], 1);
        for (int i = 0; i < 25; i++) s[i] ^= D[i % 5];
        for (int x = 0; x < 5; x++) for (int y = 0; y < 5; y++) B[y + 5 * ((2 * x + 3 * y) % 5)] = rl(s[x + 5 * y], R[x][y]);
        for (int x = 0; x < 5; x++) for (int y = 0; y < 5; y++) s[x + 5 * y] = B[x + 5 * y] ^ (~B[(x + 1) % 5 + 5 * y] & B[(x + 2) % 5 + 5 * y]);
        s[0] ^= HKRC[r];
    }
    for (int i = 0; i < 32; i++) out[i] = (u8)(s[i / 8] >> (8 * (i % 8)));
}
static void hsha256(const u8 *msg, size_t len, u8 out[32]) {
    static const u32 K[64] = {
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3,
        0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
        0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13,
        0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
        0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3, 0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208,
        0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2 };
    u32 H[8] = { 0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19 };
    std::vector<u8> m(msg, msg + len); m.push_back(0x80);
    while (m.size() % 64 != 56) m.push_back(0);
    u64 bits = (u64)len * 8; for (int i = 7; i >= 0; i--) m.push_back((u8)(bits >> (8 * i)));
    auto rr = [](u32 x, int n) { return (x >> n) | (x << (32 - n)); };
    for (size_t o = 0; o < m.size(); o += 64) {
        u32 w[64];
        for (int i = 0; i < 16; i++) w[i] = (u32)m[o + 4 * i] << 24 | (u32)m[o + 4 * i + 1] << 16 | (u32)m[o + 4 * i + 2] << 8 | m[o + 4 * i + 3];
        for (int i = 16; i < 64; i++) w[i] = w[i - 16] + (rr(w[i - 15], 7) ^ rr(w[i - 15], 18) ^ (w[i - 15] >> 3)) + w[i - 7] + (rr(w[i - 2], 17) ^ rr(w[i - 2], 19) ^ (w[i - 2] >> 10));
        u32 a = H[0], b = H[1], c = H[2], d = H[3], e = H[4], f = H[5], g = H[6], h = H[7];
        for (int i = 0; i < 64; i++) {
            u32 t1 = h + (rr(e, 6) ^ rr(e, 11) ^ rr(e, 25)) + ((e & f) ^ (~e & g)) + K[i] + w[i];
            u32 t2 = (rr(a, 2) ^ rr(a, 13) ^ rr(a, 22)) + ((a & b) ^ (a & c) ^ (b & c));
            h = g; g = f; f = e; e = d + t1; d = c; c = b; b = a; a = t1 + t2;
        }
        H[0] += a; H[1] += b; H[2] += c; H[3] += d; H[4] += e; H[5] += f; H[6] += g; H[7] += h;
    }
    for (int i = 0; i < 32; i++) out[i] = (u8)(H[i / 4] >> (24 - 8 * (i % 4)));
}
static const char B58[] = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
static std::string b58_bytes(const u8 *in, int n) {
    std::vector<u8> buf(in, in + n);
    int zeros = 0; while (zeros < n && buf[zeros] == 0) zeros++;
    std::string tmp; int start = zeros;
    while (start < n) {
        int rem = 0;
        for (int i = start; i < n; i++) { int v = (rem << 8) | buf[i]; buf[i] = (u8)(v / 58); rem = v % 58; }
        tmp.push_back(B58[rem]);
        while (start < n && buf[start] == 0) start++;
    }
    std::string out(zeros, '1'); out.append(tmp.rbegin(), tmp.rend());
    return out;
}
// private key (8 LE words) -> 25 address bytes
static void ref_address(const u32 *k, u8 addr[25]) {
    HPt p = hmulG(k);
    u8 xy[64];
    for (int i = 0; i < 32; i++) { xy[i] = (u8)(p.x[7 - i / 4] >> (24 - 8 * (i % 4))); xy[32 + i] = (u8)(p.y[7 - i / 4] >> (24 - 8 * (i % 4))); }
    u8 h[32], d1[32], d2[32];
    hkeccak256(xy, 64, h);
    addr[0] = 0x41; memcpy(addr + 1, h + 12, 20);
    hsha256(addr, 21, d1); hsha256(d1, 32, d2);
    memcpy(addr + 21, d2, 4);
}
static std::string key_hex(const u32 *k) {
    char s[65];
    for (int i = 0; i < 8; i++) snprintf(s + 8 * i, 9, "%08x", k[7 - i]);
    return std::string(s, 64);
}
// k = k0(counter) + offset (mod n)
static void key_of(const u32 key[8], u64 counter, int offset, u32 k[8]) {
    u32 w[8], k0[8];
    chacha12(key, counter, w);
    scalar_from_words(k0, w);
    u32 o[8] = {0};
    if (offset >= 0) { o[0] = (u32)offset; haddm(k, k0, o, HN); }
    else { o[0] = (u32)(-offset); hsubm(k, k0, o, HN); }
}

