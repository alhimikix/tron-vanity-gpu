        CC_QR(x0, x4, x8, x12); CC_QR(x1, x5, x9, x13); CC_QR(x2, x6, x10, x14); CC_QR(x3, x7, x11, x15);
        CC_QR(x0, x5, x10, x15); CC_QR(x1, x6, x11, x12); CC_QR(x2, x7, x8, x13); CC_QR(x3, x4, x9, x14);
    }
    out[0] = x0 + 0x61707865; out[1] = x1 + 0x3320646e; out[2] = x2 + 0x79622d32; out[3] = x3 + 0x6b206574;
    out[4] = x4 + key[0]; out[5] = x5 + key[1]; out[6] = x6 + key[2]; out[7] = x7 + key[3];
}
// group order n, little-endian words
#define N_WORDS { 0xD0364141u, 0xBFD25E8Cu, 0xAF48A03Bu, 0xBAAEDCE6u, 0xFFFFFFFEu, 0xFFFFFFFFu, 0xFFFFFFFFu, 0xFFFFFFFFu }
// 256-bit value from ChaCha words, reduced below n (one subtraction suffices: 2^256 < 2n)
HD void scalar_from_words(u32 k[8], const u32 w[8]) {
    const u32 n[8] = N_WORDS;
    u32 d[8]; u64 b = 0;
    for (int i = 0; i < 8; i++) { u64 t = (u64)w[i] - n[i] - b; d[i] = (u32)t; b = (t >> 63) & 1; }
    for (int i = 0; i < 8; i++) k[i] = b ? w[i] : d[i];
}

