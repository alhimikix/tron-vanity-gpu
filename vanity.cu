__device__ __forceinline__ u32 ror(u32 x, int n) { return __funnelshift_r(x, x, n); }
// one SHA-256 block (16 big-endian words) from the initial state
__device__ __forceinline__ void sha256_block(const u32 m[16], u32 out[8]) {
    u32 w[16];
    #pragma unroll
    for (int i = 0; i < 16; i++) w[i] = m[i];
    u32 a = 0x6a09e667, b = 0xbb67ae85, c = 0x3c6ef372, d = 0xa54ff53a, e = 0x510e527f, f = 0x9b05688c, g = 0x1f83d9ab, h = 0x5be0cd19;
    #pragma unroll
    for (int i = 0; i < 64; i++) {
        if (i >= 16) {
            u32 w15 = w[(i - 15) & 15], w2 = w[(i - 2) & 15];
            w[i & 15] += (ror(w15, 7) ^ ror(w15, 18) ^ (w15 >> 3)) + w[(i - 7) & 15] + (ror(w2, 17) ^ ror(w2, 19) ^ (w2 >> 10));
        }
        u32 t1 = h + (ror(e, 6) ^ ror(e, 11) ^ ror(e, 25)) + ((e & f) ^ (~e & g)) + SK[i] + w[i & 15];
        u32 t2 = (ror(a, 2) ^ ror(a, 13) ^ ror(a, 22)) + ((a & b) ^ (a & c) ^ (b & c));
        h = g; g = f; f = e; e = d + t1; d = c; c = b; b = a; a = t1 + t2;
    }
    out[0] = a + 0x6a09e667; out[1] = b + 0xbb67ae85; out[2] = c + 0x3c6ef372; out[3] = d + 0xa54ff53a;
    out[4] = e + 0x510e527f; out[5] = f + 0x9b05688c; out[6] = g + 0x1f83d9ab; out[7] = h + 0x5be0cd19;
}

