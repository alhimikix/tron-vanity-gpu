#define MAX_PATTERNS 64
#define MAX_RANGES 64
struct Pattern { char pre[35]; char suf[35]; u8 plen, slen; };
__device__ __constant__ Pattern c_pats[MAX_PATTERNS];
__device__ __constant__ int c_npats, c_icase, c_need_ck, c_nranges;
__device__ __constant__ u32 c_bitmap[8];
__device__ __constant__ u64 c_rlo[MAX_RANGES], c_rhi[MAX_RANGES];
__device__ __constant__ char c_b58[59] = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
__device__ __constant__ u32 c_G[GRP + 1][16];       // j*G (j = 1..GRP) and STEP*G, affine x[8] y[8]
__device__ __constant__ u32 c_P2[256][16];          // 2^i * G, affine

struct Match { u64 counter; i32 offset; u8 addr[25]; u8 pad[3]; };

HD char fold(char c, int icase) { return (icase && c >= 'A' && c <= 'Z') ? (char)(c + 32) : c; }
HD int pattern_match(const char *s, int len, const Pattern &p, int icase) {
    if (p.plen > len || p.slen > len) return 0;
    for (int i = 0; i < p.plen; i++) if (fold(s[i], icase) != fold(p.pre[i], icase)) return 0;
    for (int i = 0; i < p.slen; i++) if (fold(s[len - p.slen + i], icase) != fold(p.suf[i], icase)) return 0;
    return 1;
}
// base58 of the 25-byte address (as 28 bytes with 3 leading zeros, 7 big-endian words)
HD int b58_addr(const u32 nw[7], char *out, const char *alpha) {
    u32 n[7];
    for (int i = 0; i < 7; i++) n[i] = nw[i];
    char tmp[48]; int len = 0, start = 0;
    while (start < 7 && n[start] == 0) start++;
    while (start < 7) {
        u64 rem = 0;
        for (int i = start; i < 7; i++) { u64 cur = (rem << 32) | n[i]; n[i] = (u32)(cur / 656356768ULL); rem = cur % 656356768ULL; }
        while (start < 7 && n[start] == 0) start++;
        u32 r = (u32)rem;
        for (int q = 0; q < 5; q++) { tmp[len++] = alpha[r % 58]; r /= 58; }
    }
    while (len > 0 && tmp[len - 1] == alpha[0]) len--;
    for (int i = 0; i < len; i++) out[i] = tmp[len - 1 - i];
    out[len] = 0;
    return len;
}

struct SearchParams {
    u32 key[8];
    u64 base;          // chunk counter of thread 0, chunk 0
    u32 chunks;        // random starts per thread per launch
    Match *m; u32 *nm; u32 mcap;
    u8 *dump;          // optional: every address of the first chunk of thread 0 (selftest)
};

__device__ __forceinline__ void check_point(const SearchParams &P, fe x, fe y, u64 counter, int offset) {
    fe_canon(x); fe_canon(y);
    u64 s[25];
    #pragma unroll
    for (int i = 0; i < 25; i++) s[i] = 0;
    #pragma unroll
    for (int i = 0; i < 4; i++) {
        s[i] = (u64)bswap32(x[7 - 2 * i]) | ((u64)bswap32(x[6 - 2 * i]) << 32);
        s[4 + i] = (u64)bswap32(y[7 - 2 * i]) | ((u64)bswap32(y[6 - 2 * i]) << 32);
    }
    s[8] = 1; s[16] = 0x8000000000000000ULL;
    keccakf(s);
    // address A = 0x41 || hash[12..32), as big-endian words: A word j covers bytes 4j..4j+3 of (A || ck)
    u32 hb[5];   // hash bytes 12..31 as big-endian words
    hb[0] = bswap32((u32)(s[1] >> 32));
    hb[1] = bswap32((u32)s[2]); hb[2] = bswap32((u32)(s[2] >> 32));
    hb[3] = bswap32((u32)s[3]); hb[4] = bswap32((u32)(s[3] >> 32));
    u64 top = ((u64)0x41 << 56) | ((u64)hb[0] << 24) | (hb[1] >> 8);
    u32 ck = 0;
    bool have_ck = false;
    auto checksum = [&]() {
        u32 m[16];
        m[0] = 0x41000000u | (hb[0] >> 8);
        for (int i = 1; i < 5; i++) m[i] = (hb[i - 1] << 24) | (hb[i] >> 8);
        m[5] = (hb[4] << 24) | 0x00800000u;
        for (int i = 6; i < 15; i++) m[i] = 0;
        m[15] = 21 * 8;
        u32 d1[8], d2[8];
        sha256_block(m, d1);
        for (int i = 0; i < 8; i++) m[i] = d1[i];
        m[8] = 0x80000000u;
        for (int i = 9; i < 15; i++) m[i] = 0;
        m[15] = 256;
        sha256_block(m, d2);
        ck = d2[0];
        have_ck = true;
    };
    bool pass = false;
    if (c_need_ck) {
        checksum();
        u32 low = ck & 0xff;
        pass = (c_bitmap[low >> 5] >> (low & 31)) & 1;
    }
    if (!pass && c_nranges) {
        for (int r = 0; r < c_nranges; r++) if (top >= c_rlo[r] && top <= c_rhi[r]) { pass = true; break; }
    }
    if (!pass && !P.dump) return;
    if (!have_ck) checksum();
    // N = 00 00 00 41 | h[0..20) | ck, seven big-endian words
    u32 nw[7];
    nw[0] = 0x41;
    for (int i = 0; i < 5; i++) nw[1 + i] = hb[i];
    nw[6] = ck;
    if (P.dump) {
        int idx = offset + GRP;
        u8 *o = P.dump + (size_t)idx * 25;
        o[0] = 0x41;
        for (int i = 0; i < 20; i++) o[1 + i] = (u8)(hb[i >> 2] >> (24 - 8 * (i & 3)));
        for (int i = 0; i < 4; i++) o[21 + i] = (u8)(ck >> (24 - 8 * i));
        if (!pass) return;
    }
    char str[40];
    int len = b58_addr(nw, str, c_b58);
    for (int p = 0; p < c_npats; p++) {
        if (!pattern_match(str, len, c_pats[p], c_icase)) continue;
        u32 slot = atomicAdd(P.nm, 1);
        if (slot < P.mcap) {
            Match &m = P.m[slot];
            m.counter = counter; m.offset = offset;
            m.addr[0] = 0x41;
            for (int i = 0; i < 20; i++) m.addr[1 + i] = (u8)(hb[i >> 2] >> (24 - 8 * (i & 3)));
            for (int i = 0; i < 4; i++) m.addr[21 + i] = (u8)(ck >> (24 - 8 * i));
        }
        return;
    }
}

// P (Jacobian) += Q (affine); P must not be infinity and P != +-Q
__device__ __forceinline__ void jac_madd(fe X, fe Y, fe Z, const u32 *qx, const u32 *qy) {
    fe z2, u2, s2, h, r, h2, h3, v, t;
    fe_sq(z2, Z);
    fe_mul(u2, qx, z2);
    fe_mul(s2, qy, z2); fe_mul(s2, s2, Z);
    fe_sub(h, u2, X);
    fe_sub(r, s2, Y);
    fe_sq(h2, h); fe_mul(h3, h, h2);
    fe_mul(v, X, h2);
    fe_sq(t, r); fe_sub(t, t, h3); fe_sub(t, t, v); fe_sub(X, t, v);       // X3 = r^2 - h^3 - 2v
    fe_sub(t, v, X); fe_mul(t, r, t); fe_mul(h3, Y, h3); fe_sub(Y, t, h3); // Y3 = r(v - X3) - Y1 h^3
    fe_mul(Z, Z, h);
}

__global__ void __launch_bounds__(THREADS) k_search(SearchParams P) {
    const u32 gid = blockIdx.x * blockDim.x + threadIdx.x;
    for (u32 ch = 0; ch < P.chunks; ch++) {
        u64 counter = P.base + (u64)gid * P.chunks + ch;
        u32 w[8], k[8];
        chacha12(P.key, counter, w);
        scalar_from_words(k, w);
        // P0 = k * G from the 2^i * G table
        fe X, Y, Z;
        bool inf = true;
        for (int i = 0; i < 256; i++) {
            if (!((k[i >> 5] >> (i & 31)) & 1)) continue;
            if (inf) {
                for (int q = 0; q < 8; q++) { X[q] = c_P2[i][q]; Y[q] = c_P2[i][8 + q]; Z[q] = 0; }
                Z[0] = 1; inf = false;
            } else {
                jac_madd(X, Y, Z, c_P2[i], c_P2[i] + 8);
            }
        }
        fe x, y, zi, zi2;
        fe_inv(zi, Z); fe_sq(zi2, zi);
        fe_mul(x, X, zi2); fe_mul(zi2, zi2, zi); fe_mul(y, Y, zi2);

        fe pre[GRP + 1];
        for (int r = 0; r < ROUNDS; r++) {
            int base_off = r * STEP;
            { fe cx, cy; fe_copy(cx, x); fe_copy(cy, y); check_point(P, cx, cy, counter, base_off); }
            // prefix products of dx_j = x(jG) - x
            for (int j = 0; j <= GRP; j++) {
                fe dx;
                fe_sub(dx, c_G[j], x);
                if (j == 0) fe_copy(pre[0], dx); else fe_mul(pre[j], pre[j - 1], dx);
            }
            fe inv;
            fe_inv(inv, pre[GRP]);
            fe nx, ny;
            for (int j = GRP; j >= 0; j--) {
                fe ij, dx, l, t, x3, y3;
                if (j > 0) fe_mul(ij, inv, pre[j - 1]); else fe_copy(ij, inv);
                fe_sub(dx, c_G[j], x);
                fe_mul(inv, inv, dx);
                const u32 *gx = c_G[j], *gy = c_G[j] + 8;
                // P + jG
                fe_sub(l, gy, y); fe_mul(l, l, ij);
                fe_sq(x3, l); fe_sub(x3, x3, x); fe_sub(x3, x3, gx);
                fe_sub(t, x, x3); fe_mul(y3, l, t); fe_sub(y3, y3, y);
                if (j == GRP) { fe_copy(nx, x3); fe_copy(ny, y3); continue; }   // next centre = P + STEP*G
                check_point(P, x3, y3, counter, base_off + j + 1);
                // P - jG: slope -(gy + y) * ij
                fe_add(l, gy, y); fe_mul(l, l, ij);
                fe_sq(x3, l); fe_sub(x3, x3, x); fe_sub(x3, x3, gx);
                fe_sub(t, x3, x); fe_mul(y3, l, t); fe_sub(y3, y3, y);
                check_point(P, x3, y3, counter, base_off - (j + 1));
            }
            fe_copy(x, nx); fe_copy(y, ny);
        }
    }
}

