static int b58_index(char c) { const char *p = strchr(B58, c); return (p && c) ? (int)(p - B58) : -1; }
struct Big {   // 320-bit little-endian, enough for the 200-bit address integer
    u32 w[10];
    Big() { memset(w, 0, sizeof(w)); }
    static Big pow2(int b) { Big r; r.w[b / 32] = 1u << (b % 32); return r; }
    void mul_add(u32 m, u32 a) { u64 c = a; for (int i = 0; i < 10; i++) { u64 v = (u64)w[i] * m + c; w[i] = (u32)v; c = v >> 32; } }
    int cmp(const Big &o) const { for (int i = 9; i >= 0; i--) if (w[i] != o.w[i]) return w[i] < o.w[i] ? -1 : 1; return 0; }
    double dbl() const { double r = 0; for (int i = 9; i >= 0; i--) r = r * 4294967296.0 + w[i]; return r; }
    Big sub1() const { Big r = *this; for (int i = 0; i < 10; i++) { if (r.w[i]--) break; } return r; }
    u64 bits136() const {   // (value >> 136) & (2^64-1)
        u64 r = 0;
        for (int b = 0; b < 64; b++) { int bit = 136 + b; if ((w[bit / 32] >> (bit % 32)) & 1) r |= 1ULL << b; }
        return r;
    }
};
static void case_variants(const std::string &s, bool icase, std::vector<std::string> &out) {
    out.assign(1, "");
    for (char ch : s) {
        std::vector<char> opts;
        if (icase && isalpha((unsigned char)ch)) {
            char lo = (char)tolower(ch), up = (char)toupper(ch);
            if (b58_index(lo) >= 0) opts.push_back(lo);
            if (b58_index(up) >= 0 && up != lo) opts.push_back(up);
        } else if (b58_index(ch) >= 0) opts.push_back(ch);
        std::vector<std::string> next;
        for (auto &o : out) for (char c : opts) next.push_back(o + c);
        out.swap(next);
        if (out.size() > 65536) { fprintf(stderr, "error: too many case variants\n"); exit(1); }
    }
}
struct Range { u64 lo, hi; };
struct PatternSet {
    std::vector<Pattern> pats; std::vector<std::string> labels;
    bool icase = false, need_ck = false;
    u32 bitmap[8] = {0};
    std::vector<Range> ranges;
    double prob = 0;
};
// Address integer N is 25 bytes, always in [0x41 * 2^192, 0x42 * 2^192) -> 34 base58 characters.
static bool build_patterns(PatternSet &ps, const std::vector<std::pair<std::string, std::string>> &in) {
    Big lo0, hi0;
    lo0.w[6] = 0x41; hi0.w[6] = 0x42;
    double span = hi0.dbl() - lo0.dbl();
    for (auto pr : in) {
        std::string pre = pr.first, suf = pr.second;
        if (!pre.empty() && pre[0] != 'T' && !(ps.icase && pre[0] == 't')) pre = "T" + pre;
        if (!pre.empty() && ps.icase && pre[0] == 't') pre[0] = 'T';
        if (pre.empty() && suf.empty()) { fprintf(stderr, "error: empty pattern\n"); return false; }
        if (pre.size() + suf.size() > 34) { fprintf(stderr, "error: pattern too long\n"); return false; }
        std::vector<std::string> pv, sv;
        case_variants(pre, ps.icase, pv); case_variants(suf, ps.icase, sv);
        if ((!pre.empty() && pv.empty()) || (!suf.empty() && sv.empty())) {
            fprintf(stderr, "error: characters outside base58 (0, O, I, l are not used)%s\n", ps.icase ? "" : "; try -i");
            return false;
        }
        if ((int)ps.pats.size() >= MAX_PATTERNS) { fprintf(stderr, "error: at most %d patterns\n", MAX_PATTERNS); return false; }
        Pattern p; memset(&p, 0, sizeof(p));
        memcpy(p.pre, pre.data(), pre.size()); p.plen = (u8)pre.size();
        memcpy(p.suf, suf.data(), suf.size()); p.slen = (u8)suf.size();
        ps.pats.push_back(p);
        ps.labels.push_back(pre + "*" + suf);
        double ppre = 1;
        if (!pre.empty()) {
            double tot = 0;
            std::vector<Range> rr;
            for (auto &v : pv) {
                Big lo, hi;
                for (char c : v) lo.mul_add(58, (u32)b58_index(c));
                for (size_t i = v.size(); i < 34; i++) lo.mul_add(58, 0);
                hi = lo;
                Big step; step.w[0] = 1; for (size_t i = v.size(); i < 34; i++) step.mul_add(58, 0);
                { u64 c = 0; for (int i = 0; i < 10; i++) { u64 t = (u64)hi.w[i] + step.w[i] + c; hi.w[i] = (u32)t; c = t >> 32; } }
                if (lo.cmp(lo0) < 0) lo = lo0;
                if (hi.cmp(hi0) > 0) hi = hi0;
                if (lo.cmp(hi) >= 0) continue;
                tot += hi.dbl() - lo.dbl();
                rr.push_back({ lo.bits136(), hi.sub1().bits136() });
            }
            if (tot == 0) { fprintf(stderr, "error: no Tron address can start with %s\n", pre.c_str()); return false; }
            ppre = tot / span;
            if (suf.empty()) ps.ranges.insert(ps.ranges.end(), rr.begin(), rr.end());
        }
        double psuf = 1;
        if (!suf.empty()) {
            ps.need_ck = true;
            int K = (int)suf.size();
            psuf = (double)sv.size() * pow(58.0, -K);
            for (auto &v : sv) {
                Big x; for (char c : v) x.mul_add(58, (u32)b58_index(c));
                u32 low = x.w[0] & 0xff; int kb = K < 8 ? K : 8; u32 m = (1u << kb) - 1;
                for (u32 b = 0; b < 256; b++) if ((b & m) == (low & m)) ps.bitmap[b >> 5] |= 1u << (b & 31);
            }
        }
        ps.prob += ppre * psuf;
    }
    std::sort(ps.ranges.begin(), ps.ranges.end(), [](const Range &a, const Range &b) { return a.lo < b.lo; });
    std::vector<Range> merged;
    for (auto &r : ps.ranges) {
        if (!merged.empty() && r.lo <= merged.back().hi + 1) merged.back().hi = std::max(merged.back().hi, r.hi);
        else merged.push_back(r);
    }
    while (merged.size() > MAX_RANGES) {
        size_t best = 0; u64 gap = ~0ULL;
        for (size_t i = 0; i + 1 < merged.size(); i++) if (merged[i + 1].lo - merged[i].hi < gap) { gap = merged[i + 1].lo - merged[i].hi; best = i; }
        merged[best].hi = merged[best + 1].hi; merged.erase(merged.begin() + best + 1);
    }
    ps.ranges = merged;
    return true;
}
static bool host_match(const PatternSet &ps, const std::string &s) {
    for (auto &p : ps.pats) if (pattern_match(s.c_str(), (int)s.size(), p, ps.icase)) return true;
    return false;
}

static void os_random(void *buf, size_t n) {
#ifdef _WIN32
    if (BCryptGenRandom(NULL, (PUCHAR)buf, (ULONG)n, BCRYPT_USE_SYSTEM_PREFERRED_RNG) != 0) { fprintf(stderr, "BCryptGenRandom failed\n"); exit(1); }
#else
    FILE *f = fopen("/dev/urandom", "rb");
    if (!f || fread(buf, 1, n, f) != n) { fprintf(stderr, "cannot read /dev/urandom\n"); exit(1); }
    fclose(f);
#endif
}

