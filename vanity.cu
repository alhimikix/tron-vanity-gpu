static void upload_tables() {
    std::vector<u32> g((GRP + 1) * 16), p2(256 * 16);
    HPt G = hG(), acc = G;
    for (int j = 1; j <= GRP; j++) {
        memcpy(&g[(j - 1) * 16], acc.x, 32); memcpy(&g[(j - 1) * 16 + 8], acc.y, 32);
        acc = hadd(acc, G);
    }
    u32 s[8] = { STEP, 0, 0, 0, 0, 0, 0, 0 };
    HPt st = hmulG(s);
    memcpy(&g[GRP * 16], st.x, 32); memcpy(&g[GRP * 16 + 8], st.y, 32);
    HPt d = G;
    for (int i = 0; i < 256; i++) { memcpy(&p2[i * 16], d.x, 32); memcpy(&p2[i * 16 + 8], d.y, 32); d = hadd(d, d); }
    CUDA_CHECK(cudaMemcpyToSymbol(c_G, g.data(), g.size() * 4));
    CUDA_CHECK(cudaMemcpyToSymbol(c_P2, p2.data(), p2.size() * 4));
}
static void upload_patterns(const PatternSet &ps) {
    int np = (int)ps.pats.size(), ic = ps.icase, nc = ps.need_ck, nr = (int)ps.ranges.size();
    std::vector<u64> lo(MAX_RANGES), hi(MAX_RANGES);
    for (int i = 0; i < nr; i++) { lo[i] = ps.ranges[i].lo; hi[i] = ps.ranges[i].hi; }
    CUDA_CHECK(cudaMemcpyToSymbol(c_pats, ps.pats.data(), sizeof(Pattern) * np));
    CUDA_CHECK(cudaMemcpyToSymbol(c_npats, &np, 4));
    CUDA_CHECK(cudaMemcpyToSymbol(c_icase, &ic, 4));
    CUDA_CHECK(cudaMemcpyToSymbol(c_need_ck, &nc, 4));
    CUDA_CHECK(cudaMemcpyToSymbol(c_nranges, &nr, 4));
    CUDA_CHECK(cudaMemcpyToSymbol(c_bitmap, ps.bitmap, 32));
    CUDA_CHECK(cudaMemcpyToSymbol(c_rlo, lo.data(), 8 * MAX_RANGES));
    CUDA_CHECK(cudaMemcpyToSymbol(c_rhi, hi.data(), 8 * MAX_RANGES));
}

struct Options {
    std::vector<std::pair<std::string, std::string>> pats;
    bool icase = false; long long count = -1; std::string out;
    double bench = 0; bool selftest = false; int device = 0; int blocks_per_sm = 0;
};
struct Stats { u64 found = 0, keys = 0, mismatch = 0, dropped = 0; };

static void process(const PatternSet &ps, const u32 key[8], const Match *m, u32 n, FILE *csv, Stats &st, long long limit, bool quiet) {
    for (u32 i = 0; i < n; i++) {
        if (limit > 0 && (long long)st.found >= limit) return;
        u32 k[8]; u8 addr[25];
        key_of(key, m[i].counter, m[i].offset, k);
        ref_address(k, addr);
        std::string a = b58_bytes(addr, 25);
        if (memcmp(addr, m[i].addr, 25) != 0 || !host_match(ps, a)) { st.mismatch++; continue; }
        if (csv) { fprintf(csv, "%s,%s\n", a.c_str(), key_hex(k).c_str()); fflush(csv); }
        st.found++;
        if (!quiet) { printf("Found #%llu: %s\n", (unsigned long long)st.found, a.c_str()); fflush(stdout); }
    }
}

static int selftest(const Options &o) {
    int fails = 0;
    {   // reference: private key 1 -> TMVQGm1qAQYVdetCeGRRkTWYYrLXuHK2HC
        u32 k[8] = {1, 0, 0, 0, 0, 0, 0, 0}; u8 a[25];
        ref_address(k, a);
        bool ok = b58_bytes(a, 25) == "TMVQGm1qAQYVdetCeGRRkTWYYrLXuHK2HC";
        printf("[%s] host reference: key 1 -> %s\n", ok ? " ok " : "FAIL", b58_bytes(a, 25).c_str());
        fails += !ok;
    }
    PatternSet ps; ps.icase = true;
    build_patterns(ps, { {"", "Ab"}, {"TL", ""}, {"", "z"}, {"TZ", "x"} });
    upload_tables(); upload_patterns(ps);
    SearchParams P; os_random(P.key, 32);
    P.base = 0; P.chunks = 1; P.mcap = 1 << 16;
    const int nkeys = ROUNDS * STEP;
    CUDA_CHECK(cudaMalloc(&P.m, sizeof(Match) * P.mcap)); CUDA_CHECK(cudaMalloc(&P.nm, 4)); CUDA_CHECK(cudaMemset(P.nm, 0, 4));
    CUDA_CHECK(cudaMalloc(&P.dump, (size_t)(nkeys + 2 * GRP) * 25));
    k_search<<<1, 1>>>(P);
    CUDA_CHECK(cudaGetLastError()); CUDA_CHECK(cudaDeviceSynchronize());
    u32 nm; CUDA_CHECK(cudaMemcpy(&nm, P.nm, 4, cudaMemcpyDeviceToHost));
    std::vector<Match> m(nm); CUDA_CHECK(cudaMemcpy(m.data(), P.m, sizeof(Match) * nm, cudaMemcpyDeviceToHost));
    std::vector<u8> dump((size_t)(nkeys + 2 * GRP) * 25);
    CUDA_CHECK(cudaMemcpy(dump.data(), P.dump, dump.size(), cudaMemcpyDeviceToHost));
    // every offset the chunk covers: -GRP .. ROUNDS*STEP - GRP - 1
    int bad = 0, checked = 0;
    for (int off = -GRP; off < nkeys - GRP; off += (off < 200 ? 1 : 37)) {
        u32 k[8]; u8 a[25];
        key_of(P.key, 0, off, k); ref_address(k, a);
        bad += memcmp(a, &dump[(size_t)(off + GRP) * 25], 25) != 0; checked++;
    }
    printf("[%s] GPU addresses vs host reference (%d keys, %d bad)\n", bad ? "FAIL" : " ok ", checked, bad);
    fails += bad != 0;
    std::vector<int> want, got;
    for (int off = -GRP; off < nkeys - GRP; off++)
        if (host_match(ps, b58_bytes(&dump[(size_t)(off + GRP) * 25], 25))) want.push_back(off);
    for (auto &x : m) got.push_back(x.offset);
    std::sort(got.begin(), got.end());
    bool mok = want == got;
    printf("[%s] GPU matcher vs host scan of %d keys (%zu expected, %zu found)\n", mok ? " ok " : "FAIL", nkeys, want.size(), got.size());
    fails += !mok;
    printf(fails ? "SELFTEST FAILED\n" : "SELFTEST PASSED\n");
    return fails ? 1 : 0;
}

