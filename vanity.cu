    0x8000000080008081ULL, 0x8000000000008080ULL, 0x0000000080000001ULL, 0x8000000080008008ULL };
__device__ __forceinline__ u64 rol64(u64 x, int n) { return (x << n) | (x >> (64 - n)); }
__device__ __forceinline__ void keccakf(u64 s[25]) {
    const int rho[24] = { 1, 3, 6, 10, 15, 21, 28, 36, 45, 55, 2, 14, 27, 41, 56, 8, 25, 43, 62, 18, 39, 61, 20, 44 };
    const int pi[24] = { 10, 7, 11, 17, 18, 3, 5, 16, 8, 21, 24, 4, 15, 23, 19, 13, 12, 2, 20, 14, 22, 9, 6, 1 };
    #pragma unroll 1
    for (int r = 0; r < 24; r++) {
        u64 c[5];
        #pragma unroll
        for (int i = 0; i < 5; i++) c[i] = s[i] ^ s[i + 5] ^ s[i + 10] ^ s[i + 15] ^ s[i + 20];
        #pragma unroll
        for (int i = 0; i < 5; i++) {
            u64 d = c[(i + 4) % 5] ^ rol64(c[(i + 1) % 5], 1);
            #pragma unroll
            for (int j = 0; j < 25; j += 5) s[j + i] ^= d;
        }
        u64 t = s[1];
        #pragma unroll
        for (int i = 0; i < 24; i++) { u64 u = s[pi[i]]; s[pi[i]] = rol64(t, rho[i]); t = u; }
        #pragma unroll
        for (int j = 0; j < 25; j += 5) {
            u64 a0 = s[j], a1 = s[j + 1], a2 = s[j + 2], a3 = s[j + 3], a4 = s[j + 4];
            s[j] = a0 ^ (~a1 & a2); s[j + 1] = a1 ^ (~a2 & a3); s[j + 2] = a2 ^ (~a3 & a4);
            s[j + 3] = a3 ^ (~a4 & a0); s[j + 4] = a4 ^ (~a0 & a1);
        }
        s[0] ^= KRC[r];
    }
}
