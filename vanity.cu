}

int main(int argc, char **argv) {
    Options o; std::vector<std::string> pos;
    for (int i = 1; i < argc; i++) {
        std::string a = argv[i];
        auto next = [&]() -> std::string { if (i + 1 >= argc) { fprintf(stderr, "%s needs a value\n", a.c_str()); exit(1); } return argv[++i]; };
        if (a == "-s" || a == "--suffix") o.pats.push_back({"", next()});
        else if (a == "-p" || a == "--prefix") o.pats.push_back({next(), ""});
        else if (a == "-m" || a == "--match") { std::string m = next(); size_t st = m.find('*'); if (st == std::string::npos) { fprintf(stderr, "--match needs '*'\n"); return 1; } o.pats.push_back({m.substr(0, st), m.substr(st + 1)}); }
        else if (a == "-i" || a == "--ignore-case") o.icase = true;
        else if (a == "-n" || a == "--count") o.count = atoll(next().c_str());
        else if (a == "-o" || a == "--out") o.out = next();
        else if (a == "-d" || a == "--device") o.device = atoi(next().c_str());
        else if (a == "--bench") o.bench = atof(next().c_str());
        else if (a == "--blocks-per-sm") o.blocks_per_sm = atoi(next().c_str());
        else if (a == "--selftest") o.selftest = true;
        else if (a == "-h" || a == "--help") { usage(); return 0; }
        else if (!a.empty() && a[0] == '-') { fprintf(stderr, "unknown option %s\n", a.c_str()); usage(); return 1; }
        else pos.push_back(a);
    }
    if (pos.size() >= 1) o.pats.push_back({"", pos[0]});
    if (pos.size() >= 2) o.count = atoll(pos[1].c_str());
    CUDA_CHECK(cudaSetDevice(o.device));
    if (o.selftest) return selftest(o);
    if (o.pats.empty()) { usage(); return 1; }

    PatternSet ps; ps.icase = o.icase;
    if (!build_patterns(ps, o.pats)) return 1;
    if (o.out.empty()) o.out = "tron_vanity_results.csv";
    cudaDeviceProp prop; CUDA_CHECK(cudaGetDeviceProperties(&prop, o.device));
    printf("Patterns:");
    for (auto &l : ps.labels) printf(" %s", l.c_str());
    printf("%s\nOdds:     1 in %.4g keys per match\nOutput:   %s\n", ps.icase ? "  (case-insensitive)" : "", 1.0 / ps.prob, o.out.c_str());
    upload_tables(); upload_patterns(ps);

    int per_sm = o.blocks_per_sm;
    if (!per_sm) CUDA_CHECK(cudaOccupancyMaxActiveBlocksPerMultiprocessor(&per_sm, k_search, THREADS, 0));
    int blocks = prop.multiProcessorCount * std::max(per_sm, 1);
    u32 nthreads = (u32)blocks * THREADS;
    u64 keys_per_launch = (u64)nthreads * ROUNDS * STEP;
    printf("GPU %d:    %s (SM %d.%d, %d SMs), %u threads, %llu keys per launch\n\n", o.device, prop.name, prop.major, prop.minor,
           prop.multiProcessorCount, nthreads, (unsigned long long)keys_per_launch);
    fflush(stdout);

    bool exists = false;
    if (FILE *f = fopen(o.out.c_str(), "r")) { exists = true; fclose(f); }
    FILE *csv = fopen(o.out.c_str(), "a");
    if (!csv) { fprintf(stderr, "cannot open %s\n", o.out.c_str()); return 1; }
    if (!exists) fprintf(csv, "address,private_key\n");
    fflush(csv);

    SearchParams P; os_random(P.key, 32); P.base = 0; P.chunks = 1; P.mcap = 1 << 16; P.dump = nullptr;
    Match *hm; u32 *hn;
    CUDA_CHECK(cudaMalloc(&P.m, sizeof(Match) * P.mcap)); CUDA_CHECK(cudaMalloc(&P.nm, 4));
    CUDA_CHECK(cudaMallocHost(&hm, sizeof(Match) * P.mcap)); CUDA_CHECK(cudaMallocHost(&hn, 4));
    Stats st;
    auto t0 = std::chrono::steady_clock::now(), tl = t0; u64 kl = 0;
    for (;;) {
        CUDA_CHECK(cudaMemset(P.nm, 0, 4));
        k_search<<<blocks, THREADS>>>(P);
        CUDA_CHECK(cudaGetLastError());
        CUDA_CHECK(cudaMemcpy(hn, P.nm, 4, cudaMemcpyDeviceToHost));
        u32 n = std::min(*hn, P.mcap);
        if (*hn > P.mcap) st.dropped += *hn - P.mcap;
        if (n) { CUDA_CHECK(cudaMemcpy(hm, P.m, sizeof(Match) * n, cudaMemcpyDeviceToHost)); process(ps, P.key, hm, n, csv, st, o.count, false); }
        P.base += (u64)nthreads * P.chunks;
        st.keys += keys_per_launch;
        auto now = std::chrono::steady_clock::now();
        double dt = std::chrono::duration<double>(now - tl).count(), el = std::chrono::duration<double>(now - t0).count();
        if (dt >= 2.0) {
            double rate = (st.keys - kl) / dt;
            fprintf(stderr, "  tried ~%15llu | %12.0f keys/sec | found: %llu | ETA/match %.3gs\n", (unsigned long long)st.keys, rate,
                    (unsigned long long)st.found, 1.0 / (ps.prob * rate));
            tl = now; kl = st.keys;
        }
        if (o.count > 0 && (long long)st.found >= o.count) break;
        if (o.bench > 0 && el >= o.bench) break;
    }
    double el = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    printf("\nDone. %llu keypairs in %.2fs (%.1fM keys/sec average). Saved to %s\n", (unsigned long long)st.found, el, st.keys / el / 1e6, o.out.c_str());
    if (st.mismatch) printf("WARNING: %llu GPU matches failed the host check and were discarded\n", (unsigned long long)st.mismatch);
    if (st.dropped) printf("WARNING: %llu matches dropped (pattern too short)\n", (unsigned long long)st.dropped);
    fclose(csv);
    return st.mismatch ? 2 : 0;
}
